import os
import sys
import subprocess
import glob
import zipfile
import shutil

ROOT = os.path.dirname(os.path.abspath(__file__))
os.chdir(ROOT)

SDK = os.path.expandvars(r"%LOCALAPPDATA%\Android\Sdk")
BT = os.path.join(SDK, "build-tools", "35.0.0")
AJ = os.path.join(SDK, "platforms", "android-34", "android.jar")
JBR = r"C:\Program Files\Android\Android Studio\jbr"
JBR_BIN = os.path.join(JBR, "bin")
JAVAC = os.path.join(JBR_BIN, "javac.exe")
KEYTOOL = os.path.join(JBR_BIN, "keytool.exe")

os.environ["JAVA_HOME"] = JBR
os.environ["PATH"] = JBR_BIN + os.pathsep + os.environ.get("PATH", "")

AAPT2 = os.path.join(BT, "aapt2.exe")
D8 = os.path.join(BT, "d8.bat")
ZIPALIGN = os.path.join(BT, "zipalign.exe")
APKSIGNER = os.path.join(BT, "apksigner.bat")
LAMBDA_STUBS = os.path.join(BT, "core-lambda-stubs.jar")

# Verify tools
for name, p in [("SDK", SDK), ("Build-tools", BT), ("android.jar", AJ), ("javac", JAVAC), ("aapt2", AAPT2)]:
    if not os.path.exists(p):
        print(f"Error: {name} not found at {p}", file=sys.stderr)
        sys.exit(1)

# Config
config_props = os.path.join(ROOT, "config.properties")
if not os.path.exists(config_props):
    shutil.copyfile(os.path.join(ROOT, "config.example.properties"), config_props)
    print("Created config.properties")

props = {}
if os.path.exists(config_props):
    with open(config_props, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                props[k.strip()] = v.strip().strip('"\'')

tmdb_key = props.get("tmdb_key", "")
tmdb_region = props.get("tmdb_region", "BR")
latitude = props.get("latitude", "-23.5505")
longitude = props.get("longitude", "-46.6333")
city = props.get("city", "São Paulo")
language = props.get("language", "pt")
currency = props.get("currency", "BRL")
temperature = props.get("temperature", "C")
disable_assistant = props.get("disable_assistant", "false").lower() == "true"

out_dir = os.path.join(ROOT, "out")
gen_dir = os.path.join(out_dir, "gen", "io", "freemytv")
classes_dir = os.path.join(out_dir, "classes")

if os.path.exists(out_dir):
    shutil.rmtree(out_dir)
os.makedirs(gen_dir, exist_ok=True)
os.makedirs(classes_dir, exist_ok=True)

# Generate Config.java
config_java = f"""package io.freemytv;

/** Generated by build script from config.properties: edit that file, not this one. */
final class Config {{
    private Config() {{}}

    static final String TMDB_KEY = "{tmdb_key}";
    static final String TMDB_REGION = "{tmdb_region}";
    static final String LATITUDE = "{latitude}";
    static final String LONGITUDE = "{longitude}";
    static final String CITY = "{city}";
    static final String LANGUAGE = "{language}";
    static final String CURRENCY = "{currency}";
    static final String TEMPERATURE = "{temperature}";
    static final boolean DISABLE_ASSISTANT = {"true" if disable_assistant else "false"};
}}
"""
with open(os.path.join(gen_dir, "Config.java"), "w", encoding="utf-8") as f:
    f.write(config_java)

print("Step 1: Compiling resources with aapt2...")
res_zip = os.path.join(out_dir, "res.zip")
res_dir = os.path.join(ROOT, "app", "res")
manifest = os.path.join(ROOT, "app", "AndroidManifest.xml")
assets_dir = os.path.join(ROOT, "app", "assets")
base_apk = os.path.join(out_dir, "base.apk")

subprocess.check_call([AAPT2, "compile", "--dir", res_dir, "-o", res_zip])

print("Step 2: Linking resources with aapt2...")
subprocess.check_call([
    AAPT2, "link",
    "-o", base_apk,
    "-I", AJ,
    "--manifest", manifest,
    "--java", os.path.join(out_dir, "gen"),
    res_zip,
    "--min-sdk-version", "31",
    "--target-sdk-version", "33",
    "-A", assets_dir,
    "-0", "ttf"
])

print("Step 3: Compiling Java sources with javac...")
java_files = glob.glob(os.path.join(ROOT, "app", "src", "**", "*.java"), recursive=True) + \
             glob.glob(os.path.join(out_dir, "gen", "**", "*.java"), recursive=True)

bootcp = f"{AJ};{LAMBDA_STUBS}"
subprocess.check_call([
    JAVAC,
    "-nowarn",
    "-Xlint:-options",
    "-source", "8",
    "-target", "8",
    "-bootclasspath", bootcp,
    "-classpath", AJ,
    "-d", classes_dir
] + java_files)

print("Step 4: Compiling bytecode to dex with d8...")
class_files = glob.glob(os.path.join(classes_dir, "**", "*.class"), recursive=True)
subprocess.check_call([
    "cmd.exe", "/c", D8,
    "--release",
    "--min-api", "31",
    "--lib", AJ,
    "--output", out_dir
] + class_files)

print("Step 5: Adding classes.dex to base.apk...")
dex_file = os.path.join(out_dir, "classes.dex")
with zipfile.ZipFile(base_apk, "a", compression=zipfile.ZIP_DEFLATED) as zf:
    zf.write(dex_file, "classes.dex")

print("Step 6: Zipalign...")
aligned_apk = os.path.join(out_dir, "aligned.apk")
subprocess.check_call([ZIPALIGN, "-f", "-p", "4", base_apk, aligned_apk])

print("Step 7: Signing APK...")
keystore = os.path.join(ROOT, "freemytv.keystore")
if not os.path.exists(keystore):
    subprocess.check_call([
        KEYTOOL,
        "-genkeypair",
        "-keystore", keystore,
        "-alias", "freemytv",
        "-keyalg", "RSA",
        "-keysize", "2048",
        "-validity", "20000",
        "-storepass", "freemytv",
        "-keypass", "freemytv",
        "-dname", "CN=Free My TV"
    ])

free_apk = os.path.join(ROOT, "FreeMyTV.apk")
subprocess.check_call([
    "cmd.exe", "/c", APKSIGNER,
    "sign",
    "--ks", keystore,
    "--ks-pass", "pass:freemytv",
    "--key-pass", "pass:freemytv",
    "--out", free_apk,
    aligned_apk
])

apk_size = os.path.getsize(free_apk) / (1024 * 1024)
print(f"Built FreeMyTV.apk ({apk_size:.2f} MB).")
